    private void actualizarListaGrafica() {
        modeloGrafico.clear();
        for (int i = 0; i < listaTareas.obtenerCantidadTareas(); i++) {
            Tarea t = listaTareas.getTarea(i);
            if (t != null) {
                modeloGrafico.addElement(t.toString());
            }
        }
    }

